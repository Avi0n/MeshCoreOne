def utf16(text):
    encoded = text.encode("utf-16-le")
    return struct.unpack("<" + "H" * (len(encoded) // 2), encoded)


def dart_hash(text):
    # Python integers are unbounded: explicitly reduce each wrapping addition.
    value = 0
    for unit in utf16(text):
        value = (value + unit) % (2**32)
        value = (value * 1025) % (2**32)
        value ^= value >> 6
    value = (value * 9) % (2**32)
    value ^= value >> 11
    value = (value * 32769) % (2**32)
    return (value % (2**30)) or 1


def pocket_hash(text, timestamp):
    payload = text.encode("utf-8") + struct.pack("<I", timestamp)
    digest = hashlib.sha256(payload).digest()
    # RFC4648 Base32 groups the same 40 bits; translate its alphabet to Crockford.
    encoded = base64.b32encode(digest[:5]).decode("ascii")
    return encoded.translate(str.maketrans(
        "ABCDEFGHIJKLMNOPQRSTUVWXYZ234567", "0123456789abcdefghjkmnpqrstvwxyz"
    ))


