    /** Device-row LoRa tuple that identifies a catalog preset. Frequency is kHz, bandwidth is Hz. */
    data class RadioPresetRf(
        val frequencyKHz: Long,
        val bandwidthHz: Long,
        val spreadingFactor: Int,
        val codingRate: Int,
    )

    /**
     * Manual picker contents for [region], plus the currently-applied preset even when county
     * gating would hide it. Matches iOS `RadioPresetSection.presets` (`isSelectable || id == active`).
     * [activePresetId] is the non-repeat match so a county preset still listed while Repeat is on
     * does not vanish from the region list.
     */
    fun selectablePresets(region: RegionSelection?, activePresetId: String?): List<RadioPreset> =
        presetsForLocale(region?.countryCode).filter {
            isSelectable(it, region) || it.id == activePresetId
        }
