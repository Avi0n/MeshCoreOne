private const val RESERVED_HASH_SIZE = 0
private const val MIN_HASH_SIZE = 1
private const val UNUSED_ENCODED = -1

/**
 * Inverse of [PATH_LEN_HASH_SIZE] and [PATH_LEN_HOP_COUNT]. The index is
 * `(hashSize - 1) * (max hop count + 1) + hopCount`. Unused slots stay negative.
 */
internal val PATH_LEN_ENCODED: IntArray = run {
    val stride = PathEncoding.MAX_HOP_COUNT + 1
    val hashSizes = PathEncoding.MAX_PATH_HASH_MODE + 1
    IntArray(hashSizes * stride) { UNUSED_ENCODED }.also { table ->
        for (encoded in PATH_LEN_HASH_SIZE.indices) {
            val hashSize = PATH_LEN_HASH_SIZE[encoded]
            if (hashSize == RESERVED_HASH_SIZE) continue
            val hopCount = PATH_LEN_HOP_COUNT[encoded]
            val index = (hashSize - MIN_HASH_SIZE) * stride + hopCount
            check(table[index] == UNUSED_ENCODED) {
                "duplicate path length for hashSize=$hashSize hopCount=$hopCount"
            }
            table[index] = encoded
        }
    }
}
